function generateExpDates(count = 20) {

    function randomDateBetween(startDate, endDate) {
        const start = startDate.getTime();
        const end = endDate.getTime();

        return new Date(
            start + Math.random() * (end - start)
        );
    }

    const dates = [];
    const today = new Date();

    // Strip off the time portion
    today.setHours(0, 0, 0, 0);

    const twoYearsAgo = new Date(today);
    twoYearsAgo.setFullYear(twoYearsAgo.getFullYear() - 2);

    const yesterday = new Date(today);
    yesterday.setDate(yesterday.getDate() - 1);

    const tomorrow = new Date(today);
    tomorrow.setDate(tomorrow.getDate() + 1);

    const sixtyDaysFromNow = new Date(today);
    sixtyDaysFromNow.setDate(sixtyDaysFromNow.getDate() + 60);

    const sixtyOneDaysFromNow = new Date(today);
    sixtyOneDaysFromNow.setDate(sixtyOneDaysFromNow.getDate() + 61);

    const twoYearsFromNow = new Date(today);
    twoYearsFromNow.setFullYear(twoYearsFromNow.getFullYear() + 2);


    const pastCount = Math.round(count * 0.33);
    const nearFutureCount = Math.round(count * 0.33);
    const farFutureCount = count - pastCount - nearFutureCount;


    // 33% - sometime during the previous two years
    for (let i = 0; i < pastCount; i++) {
        dates.push(
            randomDateBetween(twoYearsAgo, yesterday)
        );
    }


    // 33% - sometime during the next 60 days
    for (let i = 0; i < nearFutureCount; i++) {
        dates.push(
            randomDateBetween(tomorrow, sixtyDaysFromNow)
        );
    }


    // Remaining dates - more than 60 days away,
    // but less than two years away
    for (let i = 0; i < farFutureCount; i++) {
        dates.push(
            randomDateBetween(sixtyOneDaysFromNow, twoYearsFromNow)
        );
    }


    // Shuffle the array so the categories aren't grouped together
    for (let i = dates.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));

        [dates[i], dates[j]] = [dates[j], dates[i]];
    }

    return dates;
}

