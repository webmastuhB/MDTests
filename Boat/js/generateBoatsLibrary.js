function inchesToFeetAndInches(totalInches) {
    if (!Number.isInteger(totalInches) || totalInches <= 0) {
        return;
    }

    const feet = Math.floor(totalInches / 12);
    const inches = totalInches % 12;

    return `${feet}' ${inches}"`;
}
