function generateUniqueIDs(count = 20) {
    const numbers = new Set();

    while (numbers.size < count) {
        const value = Math.floor(Math.random() * 9000) + 1000;
        numbers.add(value);
    }

    return Array.from(numbers);
}

function generateLicenseNumbers(count = 20) {
    const licenseNumbers = new Set();
    const letters = "ABCDEFGHIJKLMNOPQRSTUVWXYZ";

    while (licenseNumbers.size < count) {
        const number = Math.floor(Math.random() * 9000) + 1000;

        const letter1 = letters[Math.floor(Math.random() * letters.length)];
        const letter2 = letters[Math.floor(Math.random() * letters.length)];

        const licenseNumber = `LA-${number}-${letter1}${letter2}`;

        licenseNumbers.add(licenseNumber);
    }

    return Array.from(licenseNumbers);
}

